        public static IReadOnlyList<HomeGuideChapter> Chapters { get; } = Array.AsReadOnly(chapters);

        public static IEnumerable<HomeGuideChapter> Search(string query)
        {
            query = (query ?? "").Trim();
            return chapters.Where(c => query.Length == 0 || c.Title.IndexOf(query, StringComparison.OrdinalIgnoreCase) >= 0 ||
                c.Text.IndexOf(query, StringComparison.OrdinalIgnoreCase) >= 0);
        }

        public static HomeGuideChapter Find(string id) => chapters.FirstOrDefault(c => c.Id == id);
    }
