        public IEnumerable<(CampaignJournalEntry Entry, bool Done)> SideTasks()
        {
            if (FirstTaskComplete) yield return (ventArchive, HasRead(IncidentPath));
            if (CargoReleased) yield return (cargoArchive, HasRead("/home/operator/archive/payload_transfer.log"));
            if (FragmentAccessible) yield return (armory, ArmoryAccessible);
        }

        public CampaignStage CurrentStage
        {
            get
            {
                if (!FirstTaskComplete) return CampaignStage.Ventflow;
                if (!CameraIsolated) return CampaignStage.Network;
                if (!Circuit.Commissioned || !PhaseCalibrated && !Circuit.Powered(CircuitLoad.MainDoor))
                    return CampaignStage.Power;
                if (!PhaseCalibrated) return CampaignStage.Signal;
                if (!CargoReleased) return CampaignStage.Payload;
                if (LogisticsDefense.Active) return CampaignStage.Lockdown;
                if (!FloorServiced) return CampaignStage.Minefield;
                if (!VoiceVerified) return CampaignStage.Detective;
                if (!ArchiveKeyTaken) return CampaignStage.Safe;
                if (!Containment.Complete) return CampaignStage.Containment;
                if (!RecoveryAuthorized) return CampaignStage.Recovery;
                if (CoreAvatar.RevealSeen) return CampaignStage.Epilogue;
                if (CoreAvatar.Defeated) return CampaignStage.Report;
                if (CoreAvatar.Engaged) return CampaignStage.CoreFight;
                return Transit.Destination == TransitStop.Ring && !Transit.Moving ? CampaignStage.CoreEntry : CampaignStage.Transit;
            }
        }

        public string Objective
        {
            get
            {
                var stage = CurrentStage;
                if (stage == CampaignStage.Payload &&
                    SignalPlant.BarrierRequestedOpen)
                    return "Поле снято · Идите на север к грузовой галерее";
                return Journal[(int)stage].Objective;
            }
        }
